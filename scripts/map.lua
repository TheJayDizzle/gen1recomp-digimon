  -- exempts only the 64x64 image area from that palette pass.
  local EggPicBox = {}
  EggPicBox.__index = EggPicBox
  EggPicBox.isOpaque = false

  function EggPicBox.new(game, imagePath)
    local ok, image = pcall(love.graphics.newImage, imagePath)
    return setmetatable({ game = game, image = ok and image or nil }, EggPicBox)
  end

  function EggPicBox:update()
    local input = self.game.input
    if input:wasPressed("a") or input:wasPressed("b") then
      self.game.stack:pop()
    end
  end

  function EggPicBox:draw()
    Font.drawBox(6, 4, 9, 9)
    if not self.image then return end
    local width, height = self.image:getDimensions()
    local x = math.floor((6 + 4.5) * 8 - width / 2)
    local y = math.floor((4 + 4.5) * 8 - height / 2)
    love.graphics.setColor(1, 1, 1, 1)
    love.graphics.draw(self.image, x, y)
    PaletteFX.markTrueColor(x, y, width, height)
  end

